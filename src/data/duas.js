function createCategory(id, title, titleAr, color, bg, duas) {
  return { id, title, titleAr, color, bg, duas };
}

function createDua(data) {
  return {
    sourceVerified: false,
    sourceType: 'hadith',
    ...data,
  };
}

function createQuranDua(data) {
  const { surah, ayah, sourceLabel, ...rest } = data;
  return createDua({
    ...rest,
    source: sourceLabel,
    sourceVerified: true,
    sourceType: 'quran',
    quranRef: { surah, ayah, label: sourceLabel },
  });
}

